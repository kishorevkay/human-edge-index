// Story Mode draw: 3 cases per level (12 total), every level guarantees >=1 YES and >=1 NO
// right-answer case. Third case can lean harder/easier based on running performance —
// the selection is state-only; the UI never shows difficulty.
export function drawStoryCase(level, alreadyServedIds, runningAccuracy) {
  const pool = level.cases.filter((c) => !alreadyServedIds.includes(c.id));
  const servedFromLevel = level.cases.length - pool.length;

  if (servedFromLevel === 0) {
    const yes = pool.filter((c) => c.rightAnswer === "YES");
    const no = pool.filter((c) => c.rightAnswer === "NO");
    return yes[Math.floor(Math.random() * yes.length)] || pool[0];
  }
  if (servedFromLevel === 1) {
    const yes = pool.filter((c) => c.rightAnswer === "YES");
    const no = pool.filter((c) => c.rightAnswer === "NO");
    return no[Math.floor(Math.random() * no.length)] || pool[0];
  }
  // Third case: adaptive lean, but still just a random pick from the remaining pool —
  // the "difficulty" signal is reserved for future case metadata, not exposed today.
  return pool[Math.floor(Math.random() * pool.length)];
}

export function quickGameScore(correctCount) {
  return correctCount * 20;
}

export function storyModeScore(correctCount, total = 12) {
  return Math.round((correctCount / total) * 100);
}
